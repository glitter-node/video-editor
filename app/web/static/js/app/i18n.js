let currentLanguage = "ko";

export function normalizeLanguage(value) {
  return validLanguages.has(value) ? value : "ko";
}

export function getSavedLanguage(storage) {
  try {
    const source = storage || globalThis.localStorage;
    return normalizeLanguage(source.getItem(storageKey));
  } catch {
    return "ko";
  }
}

export function setLanguage(language, storage) {
  currentLanguage = normalizeLanguage(language);
  try {
    const source = storage || globalThis.localStorage;
    source.setItem(storageKey, currentLanguage);
  } catch {}
  return currentLanguage;
}

export function getLanguage() {
  return currentLanguage;
}

export function translate(key, values = {}) {
  const text = dictionaries[currentLanguage][key] ?? dictionaries.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name] === undefined ? `{${name}}` : String(values[name]));
}

export const t = translate;

export function applyTranslations(root = document) {
  const nodes = root.querySelectorAll("[data-i18n]");
  nodes.forEach((node) => { node.textContent = translate(node.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => { node.placeholder = translate(node.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => { node.title = translate(node.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-alt]").forEach((node) => { node.alt = translate(node.dataset.i18nAlt); });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => { node.setAttribute("aria-label", translate(node.dataset.i18nAriaLabel)); });
  document.documentElement.lang = currentLanguage;
}

export function initializeLanguage(select, storage, onChange) {
  currentLanguage = getSavedLanguage(storage);
  select.value = currentLanguage;
  applyTranslations();
  select.addEventListener("change", () => {
    setLanguage(select.value, storage);
    select.value = currentLanguage;
    applyTranslations();
    onChange?.(currentLanguage);
  });
  return currentLanguage;
}
